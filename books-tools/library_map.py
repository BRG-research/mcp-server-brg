"""Build LIBRARY.md: a compact map of every book, read at the start of each session.

    python3 tools/library_map.py              # write LIBRARY.md
    python3 tools/library_map.py --gist 20    # longer one-line gists (default 12 words)
    python3 tools/library_map.py --gist 0     # titles only, for a very large library
    python3 tools/library_map.py --check      # exit 1 if LIBRARY.md is out of date

The map is the "build once, reuse" context: Claude reads one small file and knows what
every book covers and which file holds which chapter, without loading any book. Details
are then found with tools/search.py and read section by section (CLAUDE.md § 2).

For each book folder with a README.md and an INDEX.md it takes the title block from the
README and, from INDEX.md, every chapter entry: file, pages or kind, and the first sentence
of its summary cut to --gist words. Part headings in INDEX.md are kept. Rebuild after adding
or re-indexing a book; never edit LIBRARY.md by hand.
"""
import argparse, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "LIBRARY.md"
STATUS = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*(\d{4}-\d{2}-\d{2})\s*\|\s*(\w+)\s*\|")
ENTRY = re.compile(r"^(#{2,3}) \[(.+?)\]\(([^)]+)\)\s*$")
PART = re.compile(r"^(#{2,3}) (Part .+)$")


def plain(s):
    s = re.sub(r"<[^>]+>|\$`|`\$|`", "", s)
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s)
    return re.sub(r"\s+", " ", s).strip()


def title_block(book):
    """'Title — Subtitle · Author · Imprint' from the README's centred header."""
    lines = [l.strip() for l in (book / "README.md").read_text(encoding="utf-8").splitlines()]
    head = []
    for l in lines:
        if l.startswith("---") or (head and l.startswith("## ")):
            break
        if re.match(r"^(#{1,3} |\*\*|\*)", l):
            head.append(plain(l.lstrip("# ").replace("**", "").strip("*")))
    return " · ".join(h for h in head if h) or book.name


def first_sentence(text, words):
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = (m.group(1) if m else text).split()
    return " ".join(s[:words]) + ("…" if len(s) > words else "")


def processed():
    """{entry: (date, status)} from PROCESSED.md (tools/processed_status.py); None when there is no such file."""
    f = ROOT / "PROCESSED.md"
    if not f.exists():
        return None
    return {m.group(1): (m.group(2), m.group(3)) for l in f.read_text(encoding="utf-8").splitlines() if (m := STATUS.match(l))}


def entries(book, words, status=None):
    lines = (book / "INDEX.md").read_text(encoding="utf-8").splitlines()
    out, i = [], 0
    while i < len(lines):
        l = lines[i]
        if m := PART.match(l):
            out.append(f"- *{plain(m.group(2))}*")
        elif m := ENTRY.match(l):
            title, file = plain(m.group(2)), m.group(3)
            st = status.get(f"{book.name}/{file}") if status is not None else None
            if status is not None and f"{book.name}/{file}" in status and st[1] != "done":
                i += 1
                continue
            meta, summary = "", ""
            j = i + 1
            while j < len(lines) and not lines[j].startswith("#"):
                t = lines[j].strip()
                if t and not meta and (t.startswith("<sub>") or re.fullmatch(r"\*[^*]+\*", t)):
                    meta = plain(t.strip("*"))
                elif t and not summary and not t.startswith(("- ", "|", "<")):
                    summary = plain(t)
                j += 1
            meta = meta.rstrip(" ·—").rstrip()
            if st:
                meta = f"{meta} · processed {st[0]}" if meta else f"processed {st[0]}"
            meta = f" ({meta})" if meta.strip(" ·—") else ""
            gist = f" — {first_sentence(summary, words)}" if summary and words > 0 else ""
            out.append(f"  - `{file}` **{title}**{meta}{gist}")
            i = j - 1
        i += 1
    return out


def build(words):
    status = processed()
    books = sorted(p for p in ROOT.iterdir() if (p / "README.md").exists() and (p / "INDEX.md").exists())
    # With PROCESSED.md, a book appears only when it is marked done (unfinished books stay hidden);
    # collections (brg-publications) appear with their done entries only.
    if status is not None:
        def shown(b):
            if b.name + "/" in status:
                return status[b.name + "/"][1] == "done"
            return any(k.startswith(b.name + "/") for k in status)  # a collection: filtered per entry
        books = [b for b in books if shown(b)]
    parts = ["# Library map", "",
             "Generated by `tools/library_map.py` — do not edit. One block per book: folder, title, "
             "then each file with its pages and a one-line gist. Read this first, then search "
             "(`python3 tools/search.py`) and open only the sections you need. Full summaries are "
             "in each book's `INDEX.md`, notation in its `GLOSSARY.md`, figures in its `FIGURES.md`.", ""]
    for b in books:
        es = entries(b, words, status)
        n = sum(1 for e in es if e.startswith("  - "))
        when = status.get(b.name + "/") if status else None
        parts += [f"## `{b.name}/` — {title_block(b)}", f"{n} files" + (f" · processed {when[0]}" if when else ""), ""] + es + [""]
    return "\n".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gist", type=int, default=12, help="words per one-line summary")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build(a.gist)
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("LIBRARY.md is up to date" if ok else "LIBRARY.md is out of date: run tools/library_map.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    w = len(text.split())
    print(f"wrote LIBRARY.md: {w} words, ~{round(w * 1.4 / 1000)}k tokens")


if __name__ == "__main__":
    sys.exit(main())
