"""Build PROCESSED.md: the processing date and status of every book and paper in the R2 library.

    aws --profile r2-books --endpoint-url <R2> s3 ls --recursive s3://brg-books/ > ls.txt
    python3 -I tools/processed_status.py ls.txt pub-README.md [old PROCESSED.md] > PROCESSED.md

library_map.py reads PROCESSED.md: only entries with status `done` go into LIBRARY.md (and so onto the
course website and into MCP retrieval), each with its processing date. Status values:
  done     fully processed and proofread
  pending  published but not finished (e.g. automatic extraction, not yet proofread)
Dates come from the old PROCESSED.md when the entry is already there and unchanged in status; otherwise
from the newest R2 upload of the book folder (or of the paper's paper.md). Set a book to `pending` by
hand while it is being processed; flip it to `done` (with today's date) when it is finished.
"""
import re, sys

ls_file, readme = sys.argv[1], sys.argv[2]
old = {}
if len(sys.argv) > 3:
    for l in open(sys.argv[3], encoding="utf-8"):
        m = re.match(r"\|\s*`([^`]+)`\s*\|\s*(\d{4}-\d{2}-\d{2})\s*\|\s*(\w+)\s*\|", l)
        if m:
            old[m.group(1)] = (m.group(2), m.group(3))

books, papers = {}, {}
for l in open(ls_file, encoding="utf-8"):
    p = l.split()
    if len(p) < 4:
        continue
    date, key = p[0], " ".join(p[3:])
    top = key.split("/")[0]
    if "/" not in key or top in ("RAW", "tools"):
        continue
    if top == "brg-publications":
        m = re.match(r"(brg-publications/papers/[^/]+/paper\.md)$", key)
        if m:
            papers[m.group(1)] = date
        continue
    books[top] = max(books.get(top, ""), date)

pending = set(re.findall(r"\((papers/[^)]+/paper\.md)\)[^\n]*not yet proofread", open(readme, encoding="utf-8").read()))
rows = []
for b, d in sorted(books.items()):
    rows.append((b + "/", *old.get(b + "/", (d, "done"))))
for k, d in sorted(papers.items()):
    st = "pending" if k.removeprefix("brg-publications/") in pending else "done"
    od = old.get(k)
    rows.append((k, od[0] if od and od[1] == st else d, st))

print("# Processing status\n")
print("Generated by `tools/processed_status.py`; edit only the status of a book being processed. "
      "Only `done` entries appear in LIBRARY.md and on the course website.\n")
print("| entry | processed | status |\n|---|---|---|")
for e, d, s in rows:
    print(f"| `{e}` | {d} | {s} |")
